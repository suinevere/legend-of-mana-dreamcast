#----------------------
# | freeze.py
# | Description: Freezes lom-dc-kit for one platform and zips it with the kit data and a README for the release.
# | Author: suinevere
# | Dependencies: pyinstaller==6.11.1, port/kit/lom_dc_kit.spec
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
import argparse
import os
import subprocess
import sys
import zipfile

#----------------------
# | HERE
# | Description: This folder, which holds the spec and receives PyInstaller's build and dist folders.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
HERE = os.path.dirname(os.path.abspath(__file__))

#----------------------
# | README
# | Description: The README.txt shipped in each zip, filled with the release tag.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
README = """Legend of Mana for Dreamcast - release kit %s

This kit holds no game data. It makes the GDI from your own Legend of Mana (USA, SLUS-01013) disc image.

1. Dump your disc to a .cue and .bin (a redump-style dump; the kit checks its SHA-1).
2. Run lom-dc-kit and give it the .bin, or drag the .bin onto it.
   Windows:  lom-dc-kit.exe "Legend of Mana (USA).bin"
   Linux:    ./lom-dc-kit "Legend of Mana (USA).bin"
   macOS:    xattr -d com.apple.quarantine lom-dc-kit && ./lom-dc-kit "Legend of Mana (USA).bin"
3. It writes a "Legend of Mana (Dreamcast)" folder beside the disc, holding disc.gdi and three tracks, for GDEMU, MODE or an emulator. About 2 GB of free space is needed while it runs.

Keep the kit folder next to the program.
"""

#----------------------
# | PLATFORMS
# | Description: The release's platform names.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
PLATFORMS = ("windows-x64", "linux-x64", "macos-arm64")


#----------------------
# | write_version
# | Description: Writes port/kit/_version.py so the frozen program reports its release tag.
# | Author: suinevere
# | Dependencies: HERE
# | Globals: N/A
# | Params: tag -- release tag
# | Returns: N/A
#----------------------
def write_version(tag):
    with open(os.path.join(HERE, "_version.py"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("#----------------------\n# | _version.py\n# | Description: Generated by freeze.py with the release tag.\n"
                     "# | Author: suinevere\n# | Dependencies: N/A\n#----------------------\nVERSION = %r\n" % tag)


#----------------------
# | make_zip
# | Description: Zips the program (marked executable), the kit data under kit/ and the README.
# | Author: suinevere
# | Dependencies: README
# | Globals: N/A
# | Params: exe -- frozen program, kit_data -- kit data folder, zip_path -- output, tag -- release tag
# | Returns: N/A
#----------------------
def make_zip(exe, kit_data, zip_path, tag):
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        info = zipfile.ZipInfo(os.path.basename(exe))
        info.external_attr = 0o755 << 16
        info.compress_type = zipfile.ZIP_DEFLATED
        with open(exe, "rb") as handle:
            z.writestr(info, handle.read())
        for name in sorted(os.listdir(kit_data)):
            z.write(os.path.join(kit_data, name), "kit/" + name)
        z.writestr("README.txt", README % tag)


#----------------------
# | main
# | Description: Writes _version.py, runs PyInstaller, smoke-tests the binary's --version and builds the zip.
# | Author: suinevere
# | Dependencies: write_version, make_zip, HERE, PLATFORMS
# | Globals: N/A
# | Params: argv -- --tag --platform --kit-data --out
# | Returns: exit code
#----------------------
def main(argv=None):
    parser = argparse.ArgumentParser(description="Freeze lom-dc-kit and zip it for a release")
    parser.add_argument("--tag", required=True)
    parser.add_argument("--platform", required=True, choices=PLATFORMS)
    parser.add_argument("--kit-data", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    write_version(args.tag)
    subprocess.check_call([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                           "--distpath", os.path.join(HERE, "dist"), "--workpath", os.path.join(HERE, "build"),
                           os.path.join(HERE, "lom_dc_kit.spec")])
    exe = os.path.join(HERE, "dist", "lom-dc-kit" + (".exe" if args.platform.startswith("windows") else ""))
    reported = subprocess.check_output([exe, "--version"], text=True)
    if args.tag not in reported:
        raise SystemExit("frozen lom-dc-kit reports %r, not %s" % (reported.strip(), args.tag))
    os.makedirs(args.out, exist_ok=True)
    zip_path = os.path.join(args.out, "lom-dc-kit-%s-%s.zip" % (args.tag, args.platform))
    make_zip(exe, args.kit_data, zip_path, args.tag)
    print(zip_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
