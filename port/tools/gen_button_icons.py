#----------------------
# | gen_button_icons.py
# | Description: Writes button_icons.py from tools/assets/DC-buttons.png: each face button scaled to the sizes the PS1 art needs, its colours cut to a few, and, at small sizes, its letter redrawn crisp in a dark shade of the button. Needs Pillow, so it runs by hand and its output is committed for the converter, which must not.
# | Author: suinevere
# | Dependencies: PIL, tools/assets/DC-buttons.png
# | Globals: SHEET, CELLS, SIZES, LETTERS, OUT
# | Params: N/A
# | Returns: N/A
#----------------------
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

#----------------------
# | SHEET / CELLS / OUT
# | Description: The art sheet, the 64-pixel cell column of each face button in its top row, and the module written.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
SHEET = os.path.join(REPO, "tools", "assets", "DC-buttons.png")
CELLS = {"X": 4, "Y": 5, "B": 6, "A": 7}
OUT = os.path.join(HERE, "button_icons.py")

#----------------------
# | SIZES / SMALL_LIMIT / SMALL_COLOURS / LARGE_COLOURS / LETTER_SHADE
# | Description: Icon sizes written (the PS1 help pages' 13x12 discs and the 33x33 one), the width below which the letter is redrawn, the colours kept at each size, and the dark shade of the button the redrawn letter takes.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
SIZES = ((13, 12), (33, 33))
SMALL_LIMIT = 20
SMALL_COLOURS = 5
LARGE_COLOURS = 15
LETTER_SHADE = 0.35

#----------------------
# | LETTERS
# | Description: The 5x5 letters redrawn on small icons.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
LETTERS = {"A": ("..#..", ".#.#.", "#...#", "#####", "#...#"),
           "B": ("####.", "#...#", "####.", "#...#", "####."),
           "X": ("#...#", ".#.#.", "..#..", ".#.#.", "#...#"),
           "Y": ("#...#", ".#.#.", "..#..", "..#..", "..#..")}


#----------------------
# | button_image
# | Description: One face button cut from the sheet to its opaque pixels, inside the cell's blue grid line.
# | Author: suinevere
# | Dependencies: SHEET, CELLS
# | Globals: N/A
# | Params: letter -- A, B, X or Y
# | Returns: RGBA image
#----------------------
def button_image(letter):
    sheet = Image.open(SHEET).convert("RGBA")
    x = CELLS[letter] * 64
    cell = sheet.crop((x + 2, 2, x + 62, 62))
    return cell.crop(cell.getchannel("A").point(lambda a: 255 if a else 0).getbbox())


#----------------------
# | icon
# | Description: One icon: the button scaled to w by h, pixels under half alpha transparent, colours cut to SMALL_COLOURS or LARGE_COLOURS, and on small icons the letter redrawn centred in LETTER_SHADE of the button's brightest common colour.
# | Author: suinevere
# | Dependencies: button_image, LETTERS
# | Globals: N/A
# | Params: letter -- A, B, X or Y, w, h -- size
# | Returns: (palette as (r, g, b) tuples, rows of hex digits, 0 transparent and n palette entry n - 1)
#----------------------
def icon(letter, w, h):
    scaled = button_image(letter).resize((w, h), Image.LANCZOS)
    small = w < SMALL_LIMIT
    rgb = scaled.convert("RGB").quantize(SMALL_COLOURS if small else LARGE_COLOURS, method=Image.Quantize.MEDIANCUT)
    flat = rgb.getpalette()
    alpha = scaled.getchannel("A")
    grid = [[(rgb.getpixel((x, y)) + 1) if alpha.getpixel((x, y)) >= 128 else 0 for x in range(w)] for y in range(h)]
    palette = [tuple(flat[i * 3:i * 3 + 3]) for i in range(max(v for row in grid for v in row))]
    if small:
        counts = {}
        for row in grid:
            for v in row:
                if v:
                    counts[v] = counts.get(v, 0) + 1
        main = max(counts, key=lambda v: (counts[v] > len(grid) * 2) * sum(palette[v - 1]))
        palette.append(tuple(int(c * LETTER_SHADE) for c in palette[main - 1]))
        ox, oy = (w - 5) // 2, (h - 5) // 2
        for y, row in enumerate(LETTERS[letter]):
            for x, ch in enumerate(row):
                if ch == "#":
                    grid[oy + y][ox + x] = len(palette)
    return tuple(palette), tuple("".join("%x" % v for v in row) for row in grid)


#----------------------
# | main
# | Description: Writes OUT with every letter at every size.
# | Author: suinevere
# | Dependencies: icon, SIZES, CELLS, OUT
# | Globals: N/A
# | Params: N/A
# | Returns: 0
#----------------------
def main():
    lines = ["#----------------------",
             "# | button_icons.py",
             "# | Description: Generated by gen_button_icons.py from tools/assets/DC-buttons.png; do not edit. ICONS maps (letter, width, height) to (palette of (r, g, b), rows of hex digits, 0 transparent and n palette entry n - 1).",
             "# | Author: suinevere",
             "# | Dependencies: N/A",
             "# | Globals: ICONS",
             "# | Params: N/A",
             "# | Returns: N/A",
             "#----------------------",
             "ICONS = {"]
    for letter in sorted(CELLS):
        for w, h in SIZES:
            palette, rows = icon(letter, w, h)
            lines.append("    (%r, %d, %d): (%r,\n        (%s)),"
                         % (letter, w, h, palette, ",\n         ".join(repr(r) for r in rows)))
    lines.append("}")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
