#----------------------
# | gen_sound_sweep.py
# | Description: Writes tests/pad_scripts/sound_sweep.pad from sound_banks.SOUND_RESOURCES: new_game's route to GNAME's name entry, then every music resource between two 1 kHz marker tones, then every effect resource's banks.
# | Author: suinevere
# | Dependencies: port/tools/sound_banks.py, tools/sweep_check.py
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
import os
import sys

DC = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(DC, "..", "port", "tools"))

import sound_banks  # noqa: E402
import sweep_check  # noqa: E402

#----------------------
# | ROUTE
# | Description: new_game.pad's steps from the title to GNAME's name entry, which has no idle timeout (the title leaves for its attract loop after 3,600 frames).
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
ROUTE = """wait state 2
wait 600
press DOWN 6
wait 30
press CROSS 6
wait state 7
wait 240
mash CIRCLE 30 state 2
wait 600
press UP 6
wait 30
press CROSS 6
wait 240
press CROSS 6
wait 180
press CROSS 6
wait state 3
wait 300
capture gname-name-entry
"""

#----------------------
# | SONG_VBLANKS / GAP_VBLANKS / MARKER_VBLANKS / BANK_VBLANKS / FRAMES_PER_SECOND
# | Description: Frames each song plays, the silence after it, the wait after each marker tone, the wait after each effect resource's uploads, and GNAME's frame rate (waits count game frames, two vblanks each there).
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
SONG_VBLANKS = 120
GAP_VBLANKS = 45
MARKER_VBLANKS = 120
BANK_VBLANKS = 20
FRAMES_PER_SECOND = 30

#----------------------
# | EFFECT_KINDS
# | Description: SOUND_RESOURCES kinds whose banks the sweep uploads; programs are registered, not uploaded.
# | Author: suinevere
# | Dependencies: N/A
# | Globals: N/A
# | Params: N/A
# | Returns: N/A
#----------------------
EFFECT_KINDS = ("effect_set", "bank", "sfx_set", "weapon_sfx")


#----------------------
# | play_frames
# | Description: Frames a song plays: SONG_VBLANKS, or for a slow-intro song enough to reach a second past its onset allowance.
# | Author: suinevere
# | Dependencies: SONG_VBLANKS, FRAMES_PER_SECOND, sweep_check.INTRO_SECONDS, sweep_check.ONSET_SECONDS
# | Globals: N/A
# | Params: resource -- music resource
# | Returns: frame count
#----------------------
def play_frames(resource):
    if resource not in sweep_check.INTRO_SECONDS:
        return SONG_VBLANKS
    return int((sweep_check.INTRO_SECONDS[resource] + sweep_check.ONSET_SECONDS + 1.0) * FRAMES_PER_SECOND)


#----------------------
# | render
# | Description: The sweep script's text.
# | Author: suinevere
# | Dependencies: ROUTE, play_frames, GAP_VBLANKS, MARKER_VBLANKS, BANK_VBLANKS, EFFECT_KINDS, sound_banks.SOUND_RESOURCES
# | Globals: N/A
# | Params: N/A
# | Returns: script text
#----------------------
def render():
    music = [r for r, kind in sound_banks.SOUND_RESOURCES if kind == "music"]
    effects = [r for r, kind in sound_banks.SOUND_RESOURCES if kind in EFFECT_KINDS]
    lines = ["# Generated by tools/gen_sound_sweep.py; do not edit. test_sound.py::test_sweep_plays_everything runs it.",
             "# Every music resource plays between two 1 kHz marker tones, then every effect resource's banks upload."]
    lines += ROUTE.splitlines()
    lines += ["musicoff", "wait %d" % GAP_VBLANKS, "tone 1000 1", "wait %d" % MARKER_VBLANKS]
    for resource in music:
        lines += ["music %d" % resource, "wait %d" % play_frames(resource), "musicoff", "wait %d" % GAP_VBLANKS]
    lines += ["tone 1000 1", "wait %d" % MARKER_VBLANKS]
    for resource in effects:
        lines += ["sfxset %d" % resource, "wait %d" % BANK_VBLANKS]
    lines.append("capture sweep-done")
    return "\n".join(lines) + "\n"


#----------------------
# | main
# | Description: Writes the script to argv[1], or to tests/pad_scripts/sound_sweep.pad.
# | Author: suinevere
# | Dependencies: render
# | Globals: N/A
# | Params: argv -- command-line arguments
# | Returns: 0
#----------------------
def main(argv):
    path = argv[1] if len(argv) > 1 else os.path.join(DC, "tests", "pad_scripts", "sound_sweep.pad")
    with open(path, "w", newline="\n") as handle:
        handle.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
