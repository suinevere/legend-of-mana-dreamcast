"""----------------------
 | gen_ram.py
 | Description: Turns Ring Ring Land's RAM map into named C accessors at the PocketStation addresses, or into a JSON field list.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""

import json
import re
import sys
from dataclasses import dataclass

"""----------------------
 | TYPES
 | Description: Map type names to their C type, size in bytes and bus width.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
TYPES = {"u8": ("uint8_t", 1, 8), "s8": ("int8_t", 1, 8), "u16": ("uint16_t", 2, 16), "s16": ("int16_t", 2, 16),
         "u32": ("uint32_t", 4, 32)}

"""----------------------
 | NO_ACCESS
 | Description: Field names that reserve bytes without accessors.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
NO_ACCESS = ("stack", "free")

"""----------------------
 | TYPE_RE
 | Description: A field type: base type with an optional element count.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
TYPE_RE = re.compile(r"^(u8|s8|u16|s16|u32)(?:\[(\d+)\])?$")


"""----------------------
 | Field
 | Description: One RAM map line.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
@dataclass
class Field:
    ps: int
    type: str
    count: int
    name: str
    vmu: object
    text: str

    @property
    def size(self) -> int:
        return TYPES[self.type][1] * self.count


"""----------------------
 | parse
 | Description: Parses the map, rejecting bad lines, duplicate names and overlapping byte ranges.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: text -- map file contents
 | Returns: list of Field in file order
 ----------------------"""
def parse(text: str) -> list:
    fields, names, owner = [], set(), {}
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].split(None, 4)
        if not line:
            continue
        m = TYPE_RE.match(line[1]) if len(line) >= 4 else None
        if not m:
            raise ValueError("line %d: expected '<ps addr> <type> <name> <vmu addr|-> [description]'" % n)
        name = line[2]
        if name in names and name not in NO_ACCESS:
            raise ValueError("line %d: %s defined twice" % (n, name))
        names.add(name)
        f = Field(int(line[0], 16), m.group(1), int(m.group(2) or 1), name,
                  None if line[3] == "-" else int(line[3], 16), line[4] if len(line) > 4 else "")
        for a in range(f.ps, f.ps + f.size):
            if a in owner:
                raise ValueError("line %d: %s overlaps %s at 0x%X" % (n, name, owner[a], a))
            owner[a] = name
        fields.append(f)
    return fields


"""----------------------
 | ps_header
 | Description: Emits ram_<name>/set_<name> accessors that go through psk_r*/psk_w* at the PocketStation address.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: fields -- parsed map
 | Returns: header text
 ----------------------"""
def ps_header(fields: list) -> str:
    out = ["/* rrl_ram.h -- generated by pocketstation/tools/gen_ram.py; do not edit. */", "#ifndef RRL_RAM_H",
           "#define RRL_RAM_H", "#include <stdint.h>", '#include "psk_hw.h"', ""]
    for f in fields:
        if f.name in NO_ACCESS:
            continue
        ctype, size, bits = TYPES[f.type]
        addr = "0x%Xu" % f.ps if f.count == 1 else "0x%Xu + %s" % (f.ps, "i" if size == 1 else "i * %du" % size)
        idx, idx_set = ("void", "") if f.count == 1 else ("uint8_t i", "uint8_t i, ")
        out.append("static inline %s ram_%s(%s) { return %spsk_r%d(%s); }" % (
            ctype, f.name, idx, "" if f.type.startswith("u") else "(%s)" % ctype, bits, addr))
        out.append("static inline void set_%s(%s%s v) { psk_w%d(%s, %sv); }" % (
            f.name, idx_set, ctype, bits, addr, "" if f.type.startswith("u") else "(uint%d_t)" % bits))
    out.append("#endif")
    return "\n".join(out) + "\n"


"""----------------------
 | fields_json
 | Description: Emits the field list both runners' state dumps are compared through.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: fields -- parsed map
 | Returns: JSON text
 ----------------------"""
def fields_json(fields: list) -> str:
    return json.dumps([{"name": f.name, "type": f.type, "count": f.count, "ps": f.ps, "vmu": f.vmu}
                       for f in fields if f.name not in NO_ACCESS], indent=1)


"""----------------------
 | main
 | Description: CLI: gen_ram.py ps|fields MAP OUT
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: argv -- command-line arguments
 | Returns: process exit code
 ----------------------"""
def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 3 or argv[0] not in ("ps", "fields"):
        print("usage: gen_ram.py ps|fields MAP OUT", file=sys.stderr)
        return 2
    try:
        with open(argv[1]) as f:
            fields = parse(f.read())
    except ValueError as e:
        print("gen_ram: %s: %s" % (argv[1], e), file=sys.stderr)
        return 1
    text = ps_header(fields) if argv[0] == "ps" else fields_json(fields)
    with open(argv[2], "w", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
