"""----------------------
 | gen_hooks.py
 | Description: Generates the runner's hook table and thunks from a hooks.txt list of decompiled functions.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""

import argparse
import re
import sys
from dataclasses import dataclass

"""----------------------
 | NAME_RE
 | Description: A C identifier.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


"""----------------------
 | Hook
 | Description: One hooks.txt line: address (bit 0 = Thumb), C name, argument count or "regs", and return type.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: N/A
 | Returns: N/A
 ----------------------"""
@dataclass
class Hook:
    addr: int
    name: str
    args: object
    ret: str
    live: int = 0x1FFFF


"""----------------------
 | parse
 | Description: Reads hooks.txt lines "<hex address> <name> <0..4|regs> [void|u32]"; '#' starts a comment.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: text -- file contents
 | Returns: list of Hook; raises ValueError on a bad line, a duplicate, or a stack-argument count
 ----------------------"""
def parse(text: str) -> list:
    hooks = []
    seen = set()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].split()
        if not line:
            continue
        if len(line) not in (3, 4) or not NAME_RE.match(line[1]):
            raise ValueError("line %d: expected '<address> <name> <0..4|regs> [void|u32]'" % n)
        addr = int(line[0], 16)
        live = 0x1FFFF
        if line[2] == "regs" or line[2].startswith("regs:"):
            args, ret = "regs", "void"
            if line[2] != "regs":
                live = 0
                for part in line[2][5:].split(","):
                    if part == "flags":
                        live |= 1 << 16
                    elif re.match(r"^r(1[0-5]|[0-9])$", part):
                        live |= 1 << int(part[1:])
                    else:
                        raise ValueError("line %d: live output %r is not r0-r15 or flags" % (n, part))
        else:
            args = int(line[2])
            if not 0 <= args <= 4:
                raise ValueError("line %d: %s takes stack arguments; give it a 'regs' replacement" % (n, line[1]))
            ret = line[3] if len(line) == 4 else "void"
            if ret not in ("void", "u32"):
                raise ValueError("line %d: return type must be void or u32" % n)
        if addr in seen:
            raise ValueError("line %d: %08X hooked twice" % (n, addr))
        seen.add(addr)
        hooks.append(Hook(addr, line[1], args, ret, live))
    return hooks


"""----------------------
 | generate
 | Description: C source with prototypes, one thunk per argument-style hook, and the psk_hooks table.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: hooks -- parsed hooks
 | Returns: the C source
 ----------------------"""
def generate(hooks: list) -> str:
    out = ["/* hooks.c -- generated by pocketstation/tools/gen_hooks.py; do not edit. */",
           "#include <stdint.h>", '#include "psk_hw.h"', "",
           "typedef struct { uint32_t addr; void (*fn)(PskCpu *c); const char *name; int regs; int result; uint32_t live; } PskHookEntry;", ""]
    for h in hooks:
        if h.args == "regs":
            out.append("void %s(PskCpu *c);" % h.name)
        else:
            params = ", ".join(["uint32_t"] * h.args) or "void"
            out.append("%s %s(%s);" % ("uint32_t" if h.ret == "u32" else "void", h.name, params))
    out.append("")
    for h in hooks:
        if h.args == "regs":
            continue
        call = "%s(%s)" % (h.name, ", ".join("c->r[%d]" % i for i in range(h.args)))
        body = ("c->r[0] = %s;" % call) if h.ret == "u32" else ("%s;" % call)
        out.append("static void thunk_%08X(PskCpu *c) { %s c->r[15] = c->r[14]; }" % (h.addr, body))
    out.append("")
    out.append("const PskHookEntry psk_hooks[] = {")
    for h in hooks:
        fn = h.name if h.args == "regs" else "thunk_%08X" % h.addr
        out.append('    {0x%08Xu, %s, "%s", %d, %d, 0x%08Xu},' % (h.addr, fn, h.name, h.args == "regs", h.ret == "u32", h.live))
    if not hooks:
        out.append("    {0u, 0, 0, 0, 0, 0u},")
    out.append("};")
    out.append("const int psk_hook_count = %d;" % len(hooks))
    return "\n".join(out) + "\n"


"""----------------------
 | main
 | Description: CLI: gen_hooks.py HOOKS_TXT OUT_C [--override FILE]; override entries replace base entries at the same address.
 | Author: suinevere
 | Dependencies: N/A
 | Globals: N/A
 | Params: argv -- command-line arguments
 | Returns: process exit code
 ----------------------"""
def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("hooks")
    ap.add_argument("out")
    ap.add_argument("--override")
    args = ap.parse_args(argv)
    paths = [args.hooks] + ([args.override] if args.override else [])
    tables = []
    for path in paths:
        with open(path) as f:
            try:
                tables.append(parse(f.read()))
            except ValueError as e:
                print("gen_hooks: %s: %s" % (path, e), file=sys.stderr)
                return 1
    hooks = tables[0]
    for h in tables[1] if len(tables) > 1 else []:
        at = [i for i, b in enumerate(hooks) if b.addr == h.addr]
        if not at:
            print("gen_hooks: %s: %08X overrides nothing" % (args.override, h.addr), file=sys.stderr)
            return 1
        hooks[at[0]] = h
    with open(args.out, "w", newline="\n") as f:
        f.write(generate(hooks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
